import os
import smtplib
from email import encoders
from email.mime.base import MIMEBase
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

BREVO_USER = os.getenv("BREVO_SMTP_USER", "")
BREVO_KEY  = os.getenv("BREVO_SMTP_KEY", "")
FROM_EMAIL = os.getenv("EMAIL_FROM", f"AudioBook Studio <{BREVO_USER}>")
SITE_URL   = os.getenv("SITE_URL", "https://books.rig360media.com")


def send_chapter_ready(
    to_email: str,
    to_name: str | None,
    chapter_title: str,
    book_title: str,
    pdf_bytes: bytes,
) -> None:
    if not BREVO_USER or not BREVO_KEY:
        return

    display_name = to_name or to_email.split("@")[0]
    from_addr = FROM_EMAIL or f"AudioBook Studio <{BREVO_USER}>"

    html = f"""<!DOCTYPE html>
<html>
<body style="margin:0;padding:0;background:#0d0d1a;font-family:-apple-system,BlinkMacSystemFont,'Inter','Segoe UI',sans-serif;">
  <table width="100%" cellpadding="0" cellspacing="0" style="padding:40px 20px;">
    <tr><td align="center">
      <table width="600" cellpadding="0" cellspacing="0" style="background:#13132b;border-radius:16px;overflow:hidden;border:1px solid #252545;">

        <tr>
          <td style="background:linear-gradient(135deg,#4c1d95,#6d28d9,#8b5cf6);padding:36px 40px;">
            <p style="margin:0;font-size:13px;color:rgba(255,255,255,0.7);letter-spacing:0.5px;text-transform:uppercase;">AudioBook Studio</p>
            <h1 style="margin:8px 0 0;font-size:26px;font-weight:800;color:#fff;">📖 {book_title}</h1>
          </td>
        </tr>

        <tr>
          <td style="padding:36px 40px;">
            <p style="margin:0 0 12px;font-size:16px;color:#c4c4e0;">Hi {display_name},</p>
            <p style="margin:0 0 20px;font-size:15px;color:#9090b8;line-height:1.6;">
              Your chapter <strong style="color:#eaeaf8;">"{chapter_title}"</strong> has been written from
              your voice recordings and is attached to this email as a PDF.
            </p>
            <div style="background:#1a1a35;border:1px solid #2e2e55;border-radius:10px;padding:20px 24px;margin-bottom:24px;">
              <p style="margin:0 0 6px;font-size:12px;color:#6060a0;text-transform:uppercase;letter-spacing:0.5px;">Want to make changes?</p>
              <p style="margin:0;font-size:14px;color:#9090b8;line-height:1.5;">
                Log in to the website to edit the manuscript, adjust wording, or re-record any section.
              </p>
            </div>
            <a href="{SITE_URL}" style="display:inline-block;padding:13px 28px;background:#7c3aed;color:#fff;border-radius:9px;text-decoration:none;font-size:14px;font-weight:700;letter-spacing:0.3px;">
              Edit on {SITE_URL.replace('https://', '')} →
            </a>
          </td>
        </tr>

        <tr>
          <td style="padding:20px 40px 28px;border-top:1px solid #1e1e38;">
            <p style="margin:0;font-size:12px;color:#404060;line-height:1.6;">
              Generated by AudioBook Studio from your voice recordings.<br>
              The PDF is attached for your records.
            </p>
          </td>
        </tr>

      </table>
    </td></tr>
  </table>
</body>
</html>"""

    safe = "".join(c for c in chapter_title if c.isalnum() or c in " _-").strip() or "chapter"

    msg = MIMEMultipart("mixed")
    msg["From"]    = from_addr
    msg["To"]      = to_email
    msg["Subject"] = f'"{chapter_title}" is published — {book_title}'
    msg.attach(MIMEText(html, "html"))

    pdf_part = MIMEBase("application", "pdf")
    pdf_part.set_payload(pdf_bytes)
    encoders.encode_base64(pdf_part)
    pdf_part.add_header("Content-Disposition", f'attachment; filename="{safe}.pdf"')
    msg.attach(pdf_part)

    with smtplib.SMTP("smtp-relay.brevo.com", 587, timeout=15) as smtp:
        smtp.ehlo()
        smtp.starttls()
        smtp.login(BREVO_USER, BREVO_KEY)
        smtp.sendmail(BREVO_USER, to_email, msg.as_string())
